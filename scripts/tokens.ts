#!/usr/bin/env node
/**
 * Trix token generator.
 *
 * Reads src/styles/tokens.css and src/styles/themes.css and writes everything
 * that derives from them:
 *
 *   src/styles/generated/fluid.css        clamp() for every -min/-max pair
 *   src/styles/generated/text-styles.css  .text-style-* classes (+ h1–h6, body)
 *   src/styles/generated/utilities.css    spacing, radius, type and span utilities
 *   src/styles/generated/tokens.ts        prop types that follow the scales
 *   design/tokens/*.tokens.json           DTCG files for Figma, one per collection × mode
 *   docs/tokens.md                        the token reference
 *
 * Usage
 *   node scripts/tokens.ts           write the files
 *   node scripts/tokens.ts --check   exit 1 if any file is out of date (CI)
 */

import {
  readFileSync,
  writeFileSync,
  mkdirSync,
  existsSync,
  readdirSync,
  rmSync,
} from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import {
  buildModel,
  fluidAt,
  layoutGrid,
  resolveColor,
  resolveVar,
  toHex,
  toPx,
  type Model,
  type Rgba,
} from "../src/utils/tokens.ts";

const HEADER =
  "/* Generated by scripts/tokens.ts from src/styles/tokens.css. Do not edit. */\n";
const ELEMENTS: Record<string, string> = {
  h1: "h1",
  h2: "h2",
  h3: "h3",
  h4: "h4",
  h5: "h5",
  h6: "h6",
  "text-main": "body",
};
const DESIGN_MIN = 320;
const DESIGN_MAX = 1440;

