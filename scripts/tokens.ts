function docs(model: Model): string {
  const fluid = new Map(model.fluid.map((f) => [f.name, f]));
  const fmt = (n: number | undefined) =>
    n === undefined ? "" : `${Math.round(n * 100) / 100}px`;
  const lines: string[] = [
    "# Token reference",
    "",
    "Generated by `npm run tokens` from `src/styles/tokens.css` and",
    "`src/styles/themes.css`. Do not edit — change the token and regenerate.",
    "",
    `Fluid values interpolate between **Mobile** (${DESIGN_MIN}px viewport) and **Desktop** (${DESIGN_MAX}px).`,
    "",
  ];
  const consumed = new Set<string>();
  for (const g of model.groups) {
    const isFluid = g.tokens.some((t) =>
      fluid.has(t.name.replace(/-(min|max)$/, "")),
    );
    lines.push(
      `## ${g.name}`,
      "",
      isFluid ? "| Token | Mobile | Desktop |" : "| Token | Value |",
      isFluid ? "| --- | --- | --- |" : "| --- | --- |",
    );
    for (const t of g.tokens) {
      if (consumed.has(t.name)) continue;
      const base = t.name.replace(/-(min|max)$/, "");
      if (fluid.has(base)) {
        if (consumed.has(base)) continue;
        consumed.add(base);
        lines.push(
          `| \`--${base}\` | ${fmt(fluidAt(model, base, DESIGN_MIN))} | ${fmt(fluidAt(model, base, DESIGN_MAX))} |`,
        );
        continue;
      }
      const resolved = t.value.includes("--font-")
        ? t.value
        : resolveVar(t.value, model.byName);
      const color = model.palette.includes(t)
        ? resolveColor(t.value, [model.byName])
        : undefined;
      const shown = color
        ? toHex(color)
        : resolved !== t.value
          ? `${t.value} → ${resolved}`
          : t.value;
      const cell = `\`${shown.replace(/\|/g, "\\|")}\``;
      lines.push(
        isFluid
          ? `| \`--${t.name}\` | ${cell} | ${cell} |`
          : `| \`--${t.name}\` | ${cell} |`,
      );
    }
    lines.push("");
  }
  if (model.byName.has("grid-columns")) {
    const r = (n: number) => `${Math.round(n * 100) / 100}px`;
    lines.push(
      "## Layout grid",
      "",
      "What `<Row>` renders inside a Section, and what each Figma frame's layout grid",
      "should be: `--grid-columns` columns, gutter `--site-gutter`, margin `--site-margin`,",
      "content capped at `--max-width-main` and centered. Phone frames are drawn on",
      "4 columns: every line of the 4-column grid is a line of the 12, one phone",
      "column is exactly `span 3`.",
      "",
      "| Frame | Design on | Margin | Gutter | Column (of 12) | Content |",
      "| --- | --- | --- | --- | --- | --- |",
    );
    const phone = toPx(model.breakpoints[0]?.value ?? "30rem") ?? 480;
    for (const w of [375, 768, 992, DESIGN_MAX, 1920]) {
      const g = layoutGrid(model, w);
      const on = w < phone ? `4 (= ${g.columns} / 3)` : `${g.columns}`;
      lines.push(
        `| ${w} | ${on} | ${r(g.margin)} | ${r(g.gutter)} | ${r(g.column)} | ${r(g.container)} |`,
      );
    }
    lines.push("");
  }
  if (model.themes.length) {
    lines.push(
      "## Themes",
      "",
      `| Token | ${model.themes.map((t) => `\`theme-${t.name}\``).join(" | ")} |`,
      `| --- | ${model.themes.map(() => "---").join(" | ")} |`,
    );
    const names = [
      ...new Set(model.themes.flatMap((t) => [...t.tokens.keys()])),
    ];
    for (const n of names) {
      const cells = model.themes.map((t) => {
        const v = t.tokens.get(n);
        if (v === undefined) return "";
        const c = resolveColor(v, [t.tokens, model.byName]);
        return c ? `\`${toHex(c)}\`` : `\`${v}\``;
      });
      lines.push(`| \`--${n}\` | ${cells.join(" | ")} |`);
    }
    lines.push("");
  }
  return lines.join("\n");
}

