function fluidCss(model: Model): string {
  const lines = model.fluid.map((f) => {
    const n = (v: string) => Number(resolveVar(v, model.byName));
    const min = `var(--${f.name}-min)`;
    const max = `var(--${f.name}-max)`;
    if (n(f.min) === n(f.max))
      return `  --${f.name}: calc(${min} / 16 * 1rem);`;
    const vmin = `var(--${f.viewportMin})`;
    const vmax = `var(--${f.viewportMax})`;
    const slope = `((${max} - ${min}) / (${vmax} - ${vmin}))`;
    const preferred = `((${min} - ${slope} * ${vmin}) / 16 * 1rem + ${slope} * 100vw)`;
    const [lo, hi] = [`${min} / 16 * 1rem`, `${max} / 16 * 1rem`];
    const [a, b] = n(f.min) > n(f.max) ? [hi, lo] : [lo, hi];
    return `  --${f.name}: clamp(${a}, ${preferred}, ${b});`;
  });
  return `${HEADER}\n:root {\n${lines.join("\n")}\n}\n`;
}

const styleClass = (name: string) => `text-style-${name.replace(/^text-/, "")}`;

function textStylesCss(model: Model): string {
  const has = (n: string) => model.byName.has(n);
  const fluidNames = new Set(model.fluid.map((f) => f.name));
  const blocks = model.textStyles.map((s) => {
    const props: [string, string][] = [
      ["font-family", `${s}-font-family`],
      ["font-size", s],
      ["font-weight", `${s}-font-weight`],
      ["line-height", `${s}-line-height`],
      ["letter-spacing", `${s}-letter-spacing`],
      ["text-transform", `${s}-text-transform`],
      ["text-wrap", `${s}-text-wrap`],
      ["--_trim-top", `${s}-trim-top`],
      ["--_trim-bottom", `${s}-trim-bottom`],
      ["--_margin-top", `${s}-margin-top`],
      ["--_margin-bottom", `${s}-margin-bottom`],
    ];
    const body = props
      .filter(([, token]) => has(token) || fluidNames.has(token))
      .map(([prop, token]) => `  ${prop}: var(--${token});`)
      .join("\n");
    const selectors = [ELEMENTS[s], `.${styleClass(s)}`]
      .filter(Boolean)
      .join(",\n");
    return `${selectors} {\n${body}\n}`;
  });
  return `${HEADER}\n${blocks.join("\n\n")}\n`;
}

function rule(selector: string, decls: string): string {
  return `.${selector} {\n${decls
    .split(";")
    .filter((d) => d.trim())
    .map((d) => `  ${d.trim()};`)
    .join("\n")}\n}`;
}

function utilitiesCss(model: Model): string {
  type Pair = [string, string];
  const steps: Pair[] = model.spaces.map((s) => [s.slice(6), `var(--${s})`]);
  const site: Pair[] = [
    ["sitemargin", "var(--site-margin)"],
    ["gutter", "var(--site-gutter)"],
  ];
  const sections: Pair[] = model.sectionSpaces.map((s) => [
    s.replace(/-/g, ""),
    `var(--section-space-${s})`,
  ]);
  const block = sections.filter(([n]) => !n.includes("overlap"));
  const out: string[] = [];
  const section = (title: string, rules: string[]) =>
    out.push(`/* ${title} */\n${rules.join("\n\n")}`);

  const padding: [string, string, Pair[]][] = [
    ["padding", "padding", [["0", "0"], ...steps, ...site, ...block]],
    [
      "padding-block",
      "padding-block",
      [["0", "0"], ...steps, ...site, ...block],
    ],
    ["padding-inline", "padding-inline", [["0", "0"], ...steps, ...site]],
    [
      "padding-top",
      "padding-top",
      [["0", "0"], ...steps, ...site, ...sections],
    ],
    [
      "padding-bottom",
      "padding-bottom",
      [["0", "0"], ...steps, ...site, ...sections],
    ],
    ["padding-left", "padding-left", [["0", "0"], ...steps, ...site]],
    ["padding-right", "padding-right", [["0", "0"], ...steps, ...site]],
  ];
  for (const [cls, prop, values] of padding) {
    section(
      `${prop}`,
      values.map(([k, v]) => rule(`${cls}-${k}`, `${prop}: ${v}`)),
    );
  }

  for (const side of ["top", "bottom", "block"]) {
    const prop = `margin-${side}`;
    const text =
      side === "block"
        ? "var(--_margin-top) var(--_margin-bottom)"
        : `var(--_margin-${side})`;
    section(prop, [
      rule(`${prop}-auto`, `${prop}: auto`),
      ...[["0", "0"], ...steps, ["gutter", "var(--site-gutter)"]].map(
        ([k, v]) => rule(`${prop}-${k}`, `${prop}: ${v}`),
      ),
      rule(`${prop}-text`, `${prop}: ${text}`),
    ]);
  }
  section("margin-inline", [rule("margin-inline-auto", "margin-inline: auto")]);

  const gap = (k: string, v: string) =>
    rule(
      `gap-${k}`,
      `grid-column-gap: var(--_gap-size); grid-row-gap: var(--_gap-size); --_gap-size: ${v}`,
    );
  section("gap", [
    rule("gap-inherit", "grid-column-gap: inherit; grid-row-gap: inherit"),
    ...[["0", "0"], ...steps, ["gutter", "var(--site-gutter)"], ...block].map(
      ([k, v]) => gap(k, v),
    ),
  ]);
  section("gap-row", [
    rule("gap-row-inherit", "grid-row-gap: inherit"),
    ...[["0", "0"], ...steps, ["gutter", "var(--site-gutter)"]].map(([k, v]) =>
      rule(`gap-row-${k}`, `grid-row-gap: ${v}`),
    ),
  ]);

  section(
    "line-height",
    model.lineHeights.map((n) =>
      rule(`line-height-${n}`, `line-height: var(--line-height-${n})`),
    ),
  );
  section(
    "letter-spacing",
    model.letterSpacings.map((n) =>
      rule(`letter-spacing-${n}`, `letter-spacing: var(--letter-spacing-${n})`),
    ),
  );
  section(
    "weight",
    model.weights.map((n) =>
      rule(
        `weight-${n}`,
        `font-family: var(--primary-family); font-weight: var(--primary-${n})`,
      ),
    ),
  );
  section("radius", [
    rule("radius-none", "border-radius: 0"),
    rule("radius-inherit", "border-radius: inherit"),
    ...model.radii.map((n) =>
      rule(`radius-${n}`, `border-radius: var(--radius-${n})`),
    ),
  ]);

  const spans = (infix: string) => [
    ...Array.from({ length: 12 }, (_, i) =>
      rule(
        `span${infix}-${i + 1}`,
        `grid-column: span ${i + 1} / span ${i + 1}`,
      ),
    ),
    rule(`span${infix}-full`, "grid-column: 1 / -1"),
  ];
  const responsive = model.breakpoints.map(
    (b) =>
      `@media (width >= ${b.value}) {\n${spans(`-${b.name}`)
        .map((r) => r.replace(/^/gm, "  "))
        .join("\n\n")}\n}`,
  );
  section("grid span (children of a Grid)", [...spans(""), ...responsive]);

  return `${HEADER}\n${out.join("\n\n")}\n`;
}

function typesTs(model: Model): string {
  const union = (values: string[]) =>
    values.map((v) => `"${v}"`).join(" | ") || "never";
  return `${HEADER.replace("/*", "//").replace(" */", "")}
/** A step of the spacing scale: \`--space-N\`. */
export type SpaceStep = ${union(model.spaces.map((s) => s.slice(6)))};
/** A section spacing size: \`--section-space-*\`, without dashes. */
export type SectionSpace = ${union(model.sectionSpaces.map((s) => s.replace(/-/g, "")))};
/** A text style: \`.text-style-*\`. */
export type TextStyle = ${union(model.textStyles.map((s) => s.replace(/^text-/, "")))};
/** A color theme: \`.theme-*\`. */
export type Theme = ${union(model.themes.map((t) => t.name))};
/** A radius: \`--radius-*\`. */
export type Radius = ${union(model.radii)};
/** A breakpoint: \`--breakpoint-*\`. */
export type Breakpoint = ${union(model.breakpoints.map((b) => b.name))};
`;
}

