type Tree = Record<string, unknown>;

function set(tree: Tree, path: string[], token: Tree) {
  let node = tree;
  for (const key of path.slice(0, -1)) node = (node[key] ??= {}) as Tree;
  node[path.at(-1)!] = token;
}

const colorValue = (c: Rgba) => ({
  colorSpace: "srgb",
  components: [c[0], c[1], c[2]].map(
    (n) => Math.round(Math.min(1, Math.max(0, n)) * 10000) / 10000,
  ),
  alpha: Math.round(c[3] * 1000) / 1000,
  hex: toHex([c[0], c[1], c[2], 1]),
});
const px = (n: number) => ({ value: Math.round(n * 100) / 100, unit: "px" });

function palettePath(name: string): string[] {
  const m = name.match(/^(.+)-(\d+)$/);
  return m ? ["color", m[1], m[2]] : ["color", name];
}

function primitivePath(model: Model, name: string): string | undefined {
  if (model.palette.some((t) => t.name === name))
    return palettePath(name).join(".");
  if (/^(primary|secondary)-family$/.test(name))
    return `font.family.${name.split("-")[0]}`;
  if (model.weights.some((w) => `primary-${w}` === name))
    return `font.weight.${name.slice(8)}`;
  if (name.startsWith("line-height-")) return `line-height.${name.slice(12)}`;
  if (name.startsWith("letter-spacing-"))
    return `letter-spacing.${name.slice(15)}`;
  if (name.startsWith("radius-")) return `radius.${name.slice(7)}`;
  return undefined;
}

const alias = (path: string) => `{${path}}`;

function families(value: string): string[] {
  return value
    .replace(
      /var\(--font-([\w-]+)\s*,?/g,
      (_, n: string) =>
        `${n.replace(/-/g, " ").replace(/\b\w/g, (c) => c.toUpperCase())},`,
    )
    .replace(/[()]/g, "")
    .split(",")
    .map((s) => s.trim().replace(/^["']|["']$/g, ""))
    .filter(Boolean);
}

function figmaFiles(model: Model): Record<string, Tree> {
  const files: Record<string, Tree> = {};
  const scope = [model.byName];

  // Primitives
  const prim: Tree = {};
  for (const t of model.palette) {
    const direct = t.value.match(/^var\(--([\w-]+)\)$/);
    const ref = direct && primitivePath(model, direct[1]);
    const c = resolveColor(t.value, scope);
    if (ref)
      set(prim, palettePath(t.name), { $type: "color", $value: alias(ref) });
    else if (c)
      set(prim, palettePath(t.name), { $type: "color", $value: colorValue(c) });
  }
  for (const f of ["primary", "secondary"]) {
    const v = model.byName.get(`${f}-family`);
    if (!v) continue;
    const ref = v.match(/^var\(--((?:primary|secondary)-family)\)$/);
    set(prim, ["font", "family", f], {
      $type: "fontFamily",
      $value: ref ? alias(primitivePath(model, ref[1])!) : families(v),
    });
  }
  for (const w of model.weights) {
    set(prim, ["font", "weight", w], {
      $type: "fontWeight",
      $value: Number(resolveVar(`var(--primary-${w})`, model.byName)),
    });
  }
  for (const n of model.lineHeights) {
    set(prim, ["line-height", n], {
      $type: "number",
      $value:
        Math.round(Number(model.byName.get(`line-height-${n}`)) * 1000) / 10,
      $description: "Percent of font size (Figma line height %).",
    });
  }
  for (const n of model.letterSpacings) {
    const em = parseFloat(model.byName.get(`letter-spacing-${n}`) ?? "0");
    set(prim, ["letter-spacing", n], {
      $type: "number",
      $value: Math.round(em * 1000) / 10,
      $description: "Percent of font size (Figma letter spacing %).",
    });
  }
  for (const n of model.radii) {
    const v =
      n === "round"
        ? 9999
        : toPx(resolveVar(`var(--radius-${n})`, model.byName));
    if (v === undefined) continue;
    set(prim, ["radius", n], { $type: "dimension", $value: px(v) });
  }
  for (const b of model.breakpoints) {
    set(prim, ["breakpoint", b.name], {
      $type: "dimension",
      $value: px(toPx(b.value) ?? 0),
    });
  }
  const columns = Number(model.byName.get("grid-columns"));
  if (columns)
    set(prim, ["grid", "columns"], {
      $type: "number",
      $value: columns,
      $description:
        "Layout grid columns on desktop and tablet frames (phone frames use 4: one is 3 of these). Margin and gutter bind to Responsive site-margin and site-gutter.",
    });
  files["Primitives.Value"] = prim;

  // Responsive — every fluid token, at both ends of the range
  for (const [mode, viewport] of [
    ["Mobile", DESIGN_MIN],
    ["Desktop", DESIGN_MAX],
  ] as const) {
    const tree: Tree = {};
    for (const f of model.fluid) {
      const v = fluidAt(model, f.name, viewport);
      if (v === undefined) continue;
      const path = model.textStyles.includes(f.name)
        ? ["font-size", f.name]
        : f.name.startsWith("section-space-")
          ? ["section-space", f.name.slice(14)]
          : f.name.startsWith("space-")
            ? ["space", f.name.slice(6)]
            : [f.name];
      set(tree, path, { $type: "dimension", $value: px(v) });
    }
    files[`Responsive.${mode}`] = tree;
  }

  // Text styles — everything but the size, as aliases where possible
  const styles: Tree = {};
  for (const s of model.textStyles) {
    for (const [prop, type] of [
      ["font-family", "fontFamily"],
      ["font-weight", "fontWeight"],
      ["line-height", "number"],
      ["letter-spacing", "number"],
    ] as const) {
      const v = model.byName.get(`${s}-${prop}`);
      const ref = v?.match(/^var\(--([\w-]+)\)$/)?.[1];
      const path = ref && primitivePath(model, ref);
      if (path) set(styles, [s, prop], { $type: type, $value: alias(path) });
    }
  }
  files["Text Styles.Value"] = styles;

  // Theme — one mode per theme
  for (const theme of model.themes) {
    const tree: Tree = {};
    for (const [name, value] of theme.tokens) {
      if (name === "color-scheme") continue;
      const direct = value.match(/^var\(--([\w-]+)\)$/)?.[1];
      if (direct && theme.tokens.has(direct)) {
        set(tree, [name], { $type: "color", $value: alias(direct) });
        continue;
      }
      const ref = direct && primitivePath(model, direct);
      if (ref) {
        set(tree, [name], { $type: "color", $value: alias(ref) });
        continue;
      }
      const c = resolveColor(value, [theme.tokens, model.byName]);
      if (c)
        set(tree, [name], {
          $type: "color",
          $value: colorValue(c),
          $description: value,
        });
    }
    const mode = theme.name.charAt(0).toUpperCase() + theme.name.slice(1);
    files[`Theme.${mode}`] = tree;
  }

  // Components — fixed component settings, px at a 16px font size
  const comp: Tree = {};
  for (const t of model.tokens.filter((x) =>
    x.group.startsWith("Components"),
  )) {
    const v = resolveVar(t.value, model.byName);
    const n = toPx(v);
    const [component, ...rest] = t.name.split("-");
    if (/^-?[\d.]+$/.test(v)) {
      set(comp, [component, rest.join("-")], {
        $type: "number",
        $value: Number(v),
      });
    } else if (n !== undefined) {
      set(comp, [component, rest.join("-")], {
        $type: "dimension",
        $value: px(n),
        ...(t.value.endsWith("em") && !t.value.endsWith("rem")
          ? {
              $description: `${t.value} — scales with the component's font size`,
            }
          : {}),
      });
    }
  }
  files["Components.Value"] = comp;
  return files;
}

